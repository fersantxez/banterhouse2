_music_init::
    ld a, #1
    ld (music_enabled), a
    xor a
    ld (music_paused), a
    ld (music_step), a
    ld (music_wait), a
    ld d, #7
    ld e, #0x38       ;; tones B/C enabled; noise disabled
    call _ay_write
    ld d, #9
    ld e, #0
    call _ay_write
    ld d, #10
    ld e, #0
    jp _ay_write

_music_tick::
    push af
    push bc
    push de
    push hl
    ld a, (music_enabled)
    or a
    jr z, music_done
    ld a, (music_paused)
    or a
    jr nz, music_done
    ld a, (music_wait)
    inc a
    cp #6
    jr c, music_store_wait
    xor a
music_store_wait:
    ld (music_wait), a
    or a
    jr nz, music_done

    ;; Melody: AY channel B.
    ld a, (music_step)
    add a, a
    ld l, a
    ld a, #0
    adc a, #0
    ld h, a
    ld bc, #pop_melody_periods
    add hl, bc
    ld e, (hl)
    inc hl
    ld d, (hl)
    push de
    ld d, #2
    pop hl
    ld e, l
    call _ay_write
    ld d, #3
    ld e, h
    call _ay_write
    ld a, (music_step)
    ld l, a
    ld h, #0
    ld bc, #pop_melody_volumes
    add hl, bc
    ld d, #9
    ld e, (hl)
    call _ay_write

    ;; Bass roots and clipped chord arpeggios: AY channel C.
    ld a, (music_step)
    add a, a
    ld l, a
    ld a, #0
    adc a, #0
    ld h, a
    ld bc, #pop_bass_arp_periods
    add hl, bc
    ld e, (hl)
    inc hl
    ld d, (hl)
    push de
    ld d, #4
    pop hl
    ld e, l
    call _ay_write
    ld d, #5
    ld e, h
    call _ay_write
    ld a, (music_step)
    ld l, a
    ld h, #0
    ld bc, #pop_bass_arp_volumes
    add hl, bc
    ld d, #10
    ld e, (hl)
    call _ay_write

    ld a, (music_step)
    inc a                 ;; byte wrap loops all 256 sixteenths
    ld (music_step), a
music_done:
    pop hl
    pop de
    pop bc
    pop af
    ret

_music_toggle::
    ld a, (music_enabled)
    xor #1
    ld (music_enabled), a
    or a
    jr z, music_toggle_off
    ld d, #7
    ld e, #0x38
    call _ay_write
    ret
music_toggle_off:
    ;; Preserve SFX channel A and silence only music-owned channels.
    ld d, #9
    ld e, #0
    call _ay_write
    ld d, #10
    ld e, #0
    call _ay_write
    ld d, #7
    ld e, #0x38
    call _ay_write
    ret

;; Pause silences only the music-owned channels and freezes the sequencer.
_music_pause::
    ld a, #1
    ld (music_paused), a
    ld d, #9
    ld e, #0
    call _ay_write
    ld d, #10
    ld e, #0
    jp _ay_write

;; Restore the currently sounding step without advancing the song position.
_music_resume::
    xor a
    ld (music_paused), a
    ld a, (music_enabled)
    or a
    ret z
    ld a, (music_step)
    or a
    ret z
    dec a
    ld l, a
    ld h, #0
    ld bc, #pop_melody_volumes
    add hl, bc
    ld d, #9
    ld e, (hl)
    call _ay_write
    ld a, (music_step)
    dec a
    ld l, a
    ld h, #0
    ld bc, #pop_bass_arp_volumes
    add hl, bc
    ld d, #10
    ld e, (hl)
    jp _ay_write
