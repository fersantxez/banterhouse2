#!/usr/bin/env python3
"""Validate the minimal M0 geometry and emit its fixed-size CPC surface table."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/levels/m0.json"
OUTPUT = ROOT / "src/generated/m0_level.h"
KINDS = {"solid": "PLAYER_SURFACE_SOLID", "one_way": "PLAYER_SURFACE_ONE_WAY"}


def generate(data):
    if data.get("schema_version") != 1 or data.get("id") != "m0":
        raise ValueError("m0: schema_version/id incompatibles")
    bounds = data.get("bounds", {})
    if bounds != {"x": 0, "y": 0, "width": 160, "height": 200}:
        raise ValueError("m0: los límites deben ser el lienzo lógico 160x200")
    spawn = data.get("spawn", {})
    if not (0 <= spawn.get("x", -1) <= 144 and 0 <= spawn.get("y", -1) <= 168):
        raise ValueError("m0: spawn fuera de límites")
    surfaces = data.get("surfaces", [])
    if len(surfaces) != 6:
        raise ValueError("m0: se requiere suelo y cinco marcas atravesables")
    ids = set()
    rows = []
    for surface in surfaces:
        sid = surface.get("id")
        kind = surface.get("kind")
        x, y = surface.get("x", -1), surface.get("y", -1)
        w, h = surface.get("width", 0), surface.get("height", 0)
        if not isinstance(sid, int) or sid in ids or not 0 <= sid <= 254:
            raise ValueError(f"m0: ID inválido o duplicado: {sid}")
        ids.add(sid)
        if kind not in KINDS:
            raise ValueError(f"m0: tipo de superficie desconocido: {kind}")
        if not all(isinstance(n, int) for n in (x, y, w, h)) or w <= 0 or h <= 0:
            raise ValueError(f"m0: rectángulo inválido para superficie {sid}")
        if x < 0 or y < 0 or x + w > 160 or y + h > 200:
            raise ValueError(f"m0: superficie {sid} sale del lienzo")
        rows.append(f"   {{{x},{y},{w},{h},{KINDS[kind]},{sid}}},")
    if sum(1 for item in surfaces if item["kind"] == "solid") != 1 or \
       sum(1 for item in surfaces if item["kind"] == "one_way") != 5:
        raise ValueError("m0: debe declarar un sólido y cinco plataformas atravesables")
    floor = next(item for item in surfaces if item["kind"] == "solid")
    if not (floor["x"] <= spawn["x"] + 3 and spawn["x"] + 13 <= floor["x"] + floor["width"] and
            spawn["y"] + 32 == floor["y"]):
        raise ValueError("m0: spawn debe apoyar sobre la superficie sólida declarada")
    geometry = json.loads((ROOT / "assets/levels/geometries/opening_arena_v1.json").read_text())
    level = json.loads((ROOT / "assets/levels/arena_01.json").read_text())
    normalized = [{"id": i, "kind": item["kind"], "x": item["x"], "y": item["y"],
                  "width": item["width"], "height": item["height"]}
                 for i, item in enumerate(geometry["surfaces"])]
    if data.get("geometry_id") != geometry["id"] or surfaces != normalized or \
       level["geometry_id"] != geometry["id"] or level["spawn"] != spawn:
        raise ValueError("m0: debe coincidir con geometry/spawn de arena_01 para el lanzamiento real")
    return "\n".join([
        "/* Generated by tools/build_m0_level.py; do not edit. */",
        "#define M0_SURFACE_COUNT 6",
        f"#define M0_SPAWN_X {spawn['x']}u",
        f"#define M0_SPAWN_Y {spawn['y']}u",
        "static const PlayerPlatform m0_surfaces[M0_SURFACE_COUNT] = {",
        *rows,
        "};",
        "",
    ])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(json.loads(SOURCE.read_text()))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("FAIL: src/generated/m0_level.h desactualizado")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
    print("PASS: m0.json válido; suelo + cinco plataformas, spawn y arena_01 sincronizados")


if __name__ == "__main__":
    main()
