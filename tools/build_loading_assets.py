#!/usr/bin/env python3
"""Pack the approved comic bitmap for the transient pre-game RAM buffer."""
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/loading'


def main():
    screen = ART / 'banterhouse2-loading.scr'
    palette = (ART / 'banterhouse2-loading.hwpal').read_bytes()
    if len(screen.read_bytes()) != 16384 or len(palette) != 16:
        raise SystemExit('Invalid loading screen/palette size')
    if any(not 0x40 <= ink <= 0x5f for ink in palette):
        raise SystemExit('Invalid Gate Array ink')
    with tempfile.TemporaryDirectory() as tmp:
        output = Path(tmp) / 'loading.zx0'
        subprocess.run([str(ROOT / 'tmp/research-tools/ZX0/src/zx0'), '-f',
                        str(screen), str(output)], check=True)
        packed = output.read_bytes()
    # Keep firmware workspace untouched during AMSDOS/tape loading.
    if len(packed) > 0x2700:
        raise SystemExit('Loading resource exceeds &8000-&A6FF boot allowance')
    lines = ['; Generated by tools/build_loading_assets.py', '.module loading_assets',
             '.area _CODE', '.globl _loading_palette', '_loading_palette::',
             '.db ' + ','.join(f'0x{x:02x}' for x in palette),
             '.area _LOADING', '.globl _loading_bitmap', '_loading_bitmap::']
    for offset in range(0, len(packed), 16):
        lines.append('.db ' + ','.join(f'0x{x:02x}' for x in packed[offset:offset+16]))
    (ROOT / 'src/generated/loading_assets.s').write_text('\n'.join(lines) + '\n')
    print(f'Loading screen: {len(packed)} packed bytes at &8000; reused after splash')


if __name__ == '__main__':
    main()
