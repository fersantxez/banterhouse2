#!/usr/bin/env python3
"""Generate CPC Mode 0 renderer variants and bank offsets from frozen sprites."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANONICAL = ROOT / "assets/source/canonical"
SPEC = importlib.util.spec_from_file_location("runtime_assets", ROOT / "tools/build_runtime_assets.py")
runtime = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(runtime)

SOURCES = (
    ("pitu_stand", "g_pitu.masked.bin", 4),
    ("pitu_walk", "g_pitu_walk.masked.bin", 4),
    ("alberto", "g_alberto.masked.bin", 6),
)


def emit_symbol(out, name, data):
    lines = [f".globl _{name}", f"_{name}::"]
    for start in range(0, len(data), 16):
        lines.append("  .db " + ",".join(f"0x{value:02x}" for value in data[start:start + 16]))
    out.append("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, default=ROOT / "build/render-assets")
    args = parser.parse_args()
    outdir = args.outdir if args.outdir.is_absolute() else ROOT / args.outdir
    outdir.mkdir(parents=True, exist_ok=True)
    asm, header = [".area _CODE"], ["/* Generated by tools/build_render_assets.py. */", "#ifndef RENDER_ASSET_LAYOUT_H", "#define RENDER_ASSET_LAYOUT_H"]
    records = []
    bank_offsets = {4: 0, 6: 0}
    for sprite_id, source, bank in SOURCES:
        raw = (CANONICAL / source).read_bytes()
        runtime.validate_sprite(raw, source)
        variants = {}
        for facing, flip in (("r", False), ("l", True)):
            for shift in (0, 1):
                data = runtime.encode_variant(raw, flip, shift)
                name = f"rg_{sprite_id}_{facing}_{shift}"
                offset = bank_offsets[bank]
                bank_offsets[bank] += len(data)
                emit_symbol(asm, name, data)
                variants[f"{facing}_{shift}"] = {"symbol": name, "offset": offset,
                                                  "bytes": len(data), "width_bytes": 8 + shift}
                header.append(f"#define {name.upper()}_OFFSET {offset}u")
                header.append(f"#define {name.upper()}_BYTES {len(data)}u")
        records.append({"id": sprite_id, "source": source,
                        "source_sha256": hashlib.sha256(raw).hexdigest(),
                        "bank": bank, "variants": variants})
    header.append("#define RENDER_ASSET_BANK4_BYTES %du" % bank_offsets[4])
    header.append("#define RENDER_ASSET_BANK6_BYTES %du" % bank_offsets[6])
    header.extend(("#endif", ""))
    (outdir / "render_assets.s").write_text("\n".join(asm) + "\n")
    (outdir / "render_asset_layout.h").write_text("\n".join(header))
    manifest = {"format": "mode0-masked-v1", "alignment_variants": "even/odd pixel x",
                "facing_variants": "right/left", "bank_bytes": bank_offsets,
                "resident_variant_bytes": bank_offsets[4] + bank_offsets[6],
                "sprites": records}
    (outdir / "render_assets.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"PASS: generated {len(records) * 4} variants; RAM4={bank_offsets[4]} B, "
          f"RAM6={bank_offsets[6]} B, total resident variants={manifest['resident_variant_bytes']} B")


if __name__ == "__main__":
    main()
