#!/usr/bin/env python3
"""Validate level JSON and generate the shared CPC campaign tables/overlays."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEVELS = ROOT / "assets/levels"
GEOMETRIES = LEVELS / "geometries"
OUT_HEADER = ROOT / "src/generated/level_data.h"
VISUALS = {"01-copias", "02-produccion", "03-calle", "04-purple"}
KINDS = {"solid", "one_way"}


def read_json(path):
    return json.loads(path.read_text())


def validate_geometry(geometry):
    bounds = geometry["bounds"]
    if geometry["outside_bottom"] not in {"clamp_to_floor", "death"}:
        raise ValueError(f"{geometry['id']}: outside_bottom inválido")
    seen = set()
    surfaces = geometry["surfaces"]
    if not surfaces or len(surfaces) > 16:
        raise ValueError(f"{geometry['id']}: cantidad de superficies fuera de 1..16")
    for surface in surfaces:
        sid = surface["id"]
        if sid in seen:
            raise ValueError(f"{geometry['id']}: ID duplicado {sid}")
        seen.add(sid)
        if surface["kind"] not in KINDS:
            raise ValueError(f"{sid}: tipo desconocido")
        x, y = surface["x"], surface["y"]
        w, h = surface["width"], surface["height"]
        if w <= 0 or h <= 0 or x < 0 or y < 0:
            raise ValueError(f"{sid}: dimensiones/coordenadas inválidas")
        if x + w > bounds["width"] or y + h > bounds["height"]:
            raise ValueError(f"{sid}: superficie fuera del escenario")
    return geometry


def validate_levels(levels, geometries):
    ids = set()
    for level in levels:
        if level["id"] in ids:
            raise ValueError(f"ID de arena duplicado: {level['id']}")
        ids.add(level["id"])
        if level["visual_id"] not in VISUALS:
            raise ValueError(f"{level['id']}: visual_id inexistente")
        if level["geometry_id"] not in geometries:
            raise ValueError(f"{level['id']}: geometry_id inexistente")
        geometry = geometries[level["geometry_id"]]
        spawn = level["spawn"]
        if not 0 <= spawn["x"] <= 144 or not 0 <= spawn["y"] <= 168:
            raise ValueError(f"{level['id']}: spawn fuera de límites")
        for surface in geometry["surfaces"]:
            if surface["kind"] != "solid":
                continue
            # Current player body is 16x32; touching a top face is valid.
            if (spawn["x"] + 3 < surface["x"] + surface["width"] and
                    surface["x"] < spawn["x"] + 13 and
                    spawn["y"] + 4 < surface["y"] + surface["height"] and
                    surface["y"] < spawn["y"] + 32):
                raise ValueError(f"{level['id']}: spawn dentro de sólido {surface['id']}")
        if len(level["machines"]) not in (1, 2, 3):
            raise ValueError(f"{level['id']}: debe tener de una a tres máquinas")
        for machine in level["machines"]:
            if machine["direction"] not in (0, 1):
                raise ValueError(f"{level['id']}: dirección inválida")
            if not any(s["y"] == machine["ground_y"] and
                       s["x"] <= machine["x"] <= s["x"] + s["width"] - 14
                       for s in geometry["surfaces"]):
                raise ValueError(f"{level['id']}: máquina sin apoyo")
    if ids != {f"arena_{i:02}" for i in range(1, 25)}:
        raise ValueError("Se requieren exactamente arena_01..arena_24")


def generate_header(levels, geometry):
    surfaces = geometry["surfaces"]
    rows = ["/* Generated by tools/build_levels.py; do not edit. */",
            f"#define LEVEL_SURFACE_COUNT {len(surfaces)}",
            f"static const Platform ledges[LEVEL_SURFACE_COUNT] = {{"]
    kind_codes = {"solid": 0, "one_way": 1}
    rows.extend(f"   {{{s['x']},{s['y']},{s['width']},{s['height']},{kind_codes[s['kind']]},{i}}}, /* {s['id']}:{s['kind']} */"
                for i, s in enumerate(surfaces))
    rows.append("};")
    rows.append("static const StageStart campaign[CAMPAIGN_SCREENS] = {")
    for level in levels:
        machines = level["machines"] + [{"x": 0, "ground_y": 0, "direction": 0}] * (3-len(level["machines"]))
        entries = ",".join(f"{{{m['x']},{m['ground_y']},{m['direction']}}}" for m in machines)
        rows.append(f"   {{{len(level['machines'])},{int(level['alberto'])},{{{entries}}}}}, /* {level['id']} {level['visual_id']} {level['geometry_id']} */")
    rows.extend(["};", ""])
    return "\n".join(rows)


def generate_overlay(level, geometry):
    image = f"../../source/canonical/{level['visual_id']}.native.png"
    spawn = level["spawn"]
    support = next((s["id"] for s in geometry["surfaces"]
                    if s["y"] == spawn["y"] + 32 and
                    s["x"] < spawn["x"] + 16 and
                    spawn["x"] < s["x"] + s["width"]), "none")
    rows = [f'<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 160 200">',
            f'<image href="{image}" width="160" height="200"/>',
            '<g fill="none" stroke="#ff2020" stroke-width="0.5">']
    for surface in geometry["surfaces"]:
        rows.append(f'<rect x="{surface["x"]}" y="{surface["y"]}" width="{surface["width"]}" height="{surface["height"]}"/>')
    rows.append('</g><g fill="#ff2020" font-family="monospace" font-size="4">')
    for surface in geometry["surfaces"]:
        rows.append(f'<text x="{surface["x"]}" y="{max(4,surface["y"]-1)}">{surface["id"]}</text>')
    rows.append(f'<rect x="{spawn["x"]}" y="{spawn["y"]}" width="16" height="32" stroke="#00ff40"/>')
    rows.append(f'<line x1="{spawn["x"]}" y1="{spawn["y"]+32}" x2="{spawn["x"]+16}" y2="{spawn["y"]+32}" stroke="#00ff40"/>')
    rows.append(f'<text x="2" y="8">{level["id"]} {level["geometry_id"]} feet={support}</text></g></svg>')
    return "\n".join(rows) + "\n"


def load_inputs(level_dir=LEVELS):
    geometries = {}
    for path in sorted((level_dir / "geometries").glob("*.json")):
        geometry = validate_geometry(read_json(path))
        geometries[geometry["id"]] = geometry
    levels = [read_json(p) for p in sorted(level_dir.glob("arena_*.json"))]
    validate_levels(levels, geometries)
    return levels, geometries


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="falla si salidas generadas no están al día")
    args = parser.parse_args()
    levels, geometries = load_inputs()
    if len(geometries) != 1:
        raise SystemExit("Esta ficha aún sólo exporta la geometría compartida del prototipo")
    geometry = next(iter(geometries.values()))
    expected = {OUT_HEADER: generate_header(levels, geometry)}
    expected.update({LEVELS / "overlays" / f"{level['id']}.svg": generate_overlay(level, geometry)
                     for level in levels})
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, content in expected.items()
                 if not path.exists() or path.read_text() != content]
        if stale:
            raise SystemExit("FAIL salidas desactualizadas: " + ", ".join(stale))
    else:
        for path, content in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"PASS: {len(levels)} arenas, {len(geometry['surfaces'])} superficies compartidas; header y overlays vigentes")


if __name__ == "__main__":
    main()
